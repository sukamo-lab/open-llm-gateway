def initialize_project(config_path: Path, env_path: Path, mode: str) -> None:
    existing = [str(path) for path in (config_path, env_path) if path.exists()]
    if existing:
        raise FileExistsError(f"refusing to overwrite existing file(s): {', '.join(existing)}")
    config_path.parent.mkdir(parents=True, exist_ok=True)
    env_path.parent.mkdir(parents=True, exist_ok=True)
    config_text = INITIAL_CONFIG
    env_text = "# Generated by llm-gateway --init\nGOOGLE_API_KEY=\n"
    if mode == "multi":
        config_text = config_text.replace("mode: single", "mode: multi", 1)
        config_text = config_text.replace("host: 127.0.0.1", "host: 0.0.0.0", 1)
        for feature in (
            "authentication", "admin_api", "managed_keys", "tenant_quotas",
            "provider_quotas", "usage_accounting", "cost_tracking", "metrics",
            "structured_logging",
        ):
            config_text = config_text.replace(f"  {feature}: false", f"  {feature}: true", 1)
        env_text += (
            f"LLM_GATEWAY_API_KEYS={secrets.token_urlsafe(48)}\n"
            f"LLM_GATEWAY_ADMIN_KEY={secrets.token_urlsafe(48)}\n"
        )
    config_path.write_text(config_text, encoding="utf-8")
    env_path.write_text(env_text, encoding="utf-8")
    if os.name != "nt":
        env_path.chmod(0o600)


def load_env_file(path: str | None) -> None:
    if not path:
        return
    env_path = Path(path)
    if not env_path.exists():
        return
    for number, raw in enumerate(env_path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].strip()
        if "=" not in line:
            raise ValueError(f"{env_path}:{number}: expected NAME=VALUE")
        name, value = line.split("=", 1)
        name, value = name.strip(), value.strip()
        if not name or not name.replace("_", "a").isalnum():
            raise ValueError(f"{env_path}:{number}: invalid environment variable name")
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
            value = value[1:-1]
        os.environ.setdefault(name, value)


def main() -> None:
    parser = argparse.ArgumentParser(description="OpenAI-compatible multi-provider LLM gateway")
    parser.add_argument("--config", default="config.yaml", help="YAML configuration path")
    parser.add_argument("--env-file", default=".env", help="environment file (default: .env)")
    parser.add_argument("--host", help="override configured bind host")
    parser.add_argument("--port", type=int, help="override configured port")
    parser.add_argument("--workers", type=int, help="override configured worker count")
    parser.add_argument("--log-level", default="info", choices=["critical", "error", "warning", "info", "debug", "trace"])
    parser.add_argument("--reload", action="store_true", help="development auto-reload")
    parser.add_argument("--check", action="store_true", help="validate configuration and exit")
    parser.add_argument("--doctor", action="store_true", help="show deployment safety diagnostics and exit")
    migrations = parser.add_mutually_exclusive_group()
    migrations.add_argument("--migration-status", action="store_true", help="show database schema versions and exit")
    migrations.add_argument("--migrate", action="store_true", help="upgrade the configured database and exit")
    parser.add_argument("--output", choices=["text", "json"], default="text", help="output format for operational commands")
    parser.add_argument("--generate-secret", action="store_true", help="generate a gateway/admin secret and exit")
    parser.add_argument("--init", action="store_true", help="create secure starter config and .env files")
    parser.add_argument("--init-mode", choices=["single", "multi"], default="single", help="profile used by --init")
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    args = parser.parse_args()

    if args.generate_secret:
        print(secrets.token_urlsafe(48))
        return
    if args.init:
        try:
            initialize_project(Path(args.config), Path(args.env_file), args.init_mode)
        except Exception as exc:
            print(f"Initialization error: {exc}", file=sys.stderr)
            raise SystemExit(2) from exc
        print(f"Created {Path(args.config).resolve()}")
        print(f"Created {Path(args.env_file).resolve()}")
        print("Add at least one provider API key, then run: llm-gateway --doctor")
        return
    try:
        load_env_file(args.env_file)
        config_path = Path(args.config).resolve()
        config = load_config(config_path)
    except Exception as exc:
        print(f"Configuration error: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc

    if args.migration_status or args.migrate:
        from .migrations import LATEST_VERSIONS

        try:
            versions = asyncio.run(migration_status(config, upgrade=args.migrate))
        except Exception as exc:
            print(f"Migration error: {type(exc).__name__}: {exc}", file=sys.stderr)
            raise SystemExit(1) from exc
        result = {
            "storage": "disabled" if not versions else (
                "postgresql" if config.database.startswith(("postgresql://", "postgres://")) else "sqlite"
            ),
            "action": "upgrade" if args.migrate else "status",
            "components": {
                name: {"current": version, "latest": LATEST_VERSIONS[name], "pending": version < LATEST_VERSIONS[name]}
                for name, version in versions.items()
            },
        }
        if args.output == "json":
            import json
            print(json.dumps(result, sort_keys=True))
        else:
            print(f"Storage: {result['storage']}")
            print(f"Action: {result['action']}")
            if not versions:
                print("Schema: not required by enabled features")
            for name, state in result["components"].items():
                label = "pending" if state["pending"] else "current"
                print(f"{name}: {state['current']} / {state['latest']} ({label})")
        return

    if args.check:
        configured = sum(p.enabled and bool(p.api_key()) for p in config.providers)
        print(f"Configuration valid: {config_path}")
        print(f"Providers: {configured} configured / {len(config.providers)} total")
        return
    if args.doctor:
        issues = config.diagnostics()
        try:
            asyncio.run(check_storage(config))
            storage_result = "OK"
        except Exception as exc:
            storage_result = "FAILED"
            issues.append(("ERROR", f"storage check failed: {type(exc).__name__}: {exc}"))
        print(f"Configuration: {config_path}")
        storage_name = (
            "disabled" if not any((config.features.provider_quotas, config.features.tenant_quotas,
                                   config.features.usage_accounting, config.features.managed_keys))
            else "PostgreSQL" if config.database.startswith(("postgresql://", "postgres://"))
            else "SQLite"
        )
        print(f"Mode: {config.mode}")
        print(f"Storage: {storage_name}")
        print(f"Storage check: {storage_result}")
        for severity, message in issues:
            print(f"{severity:5} {message}")
        errors = sum(severity == "ERROR" for severity, _ in issues)
        print(f"Result: {errors} error(s), {len(issues) - errors} warning(s)")
        raise SystemExit(2 if errors else 0)

    workers = args.workers or config.server.workers
    if args.reload and workers != 1:
        parser.error("--reload requires exactly one worker")
    os.environ["LLM_GATEWAY_CONFIG"] = str(config_path)
    if config.features.structured_logging:
        from .logging_config import configure_logging

        configure_logging(args.log_level, config.observability.include_exception_stacktraces)
    uvicorn.run(
        "llm_gateway.app:app", host=args.host or config.server.host,
        port=args.port or config.server.port, workers=workers,
        reload=args.reload, log_level=args.log_level,
        log_config=None if config.features.structured_logging else uvicorn.config.LOGGING_CONFIG,
        access_log=not config.features.structured_logging,
        proxy_headers=True, forwarded_allow_ips="127.0.0.1",
    )


if __name__ == "__main__":
    main()
